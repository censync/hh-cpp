std::function<rgb8(rgb8)> vision_transform(vision v) {
    return cached([v](vec3 lin) { return simulate(lin, v); });
}

std::function<rgb8(rgb8)> greyscale_transform() {
    return cached([](vec3 lin) { return greyscale(lin); });
}

