canvas::canvas(int width, int height, rgba8 fill)
    : width_(width),
      height_(height),
      rgba_(static_cast<std::size_t>(width) * static_cast<std::size_t>(height) * 4) {
    for (std::size_t i = 0; i < rgba_.size(); i += 4) {
        rgba_[i] = fill.r;
        rgba_[i + 1] = fill.g;
        rgba_[i + 2] = fill.b;
        rgba_[i + 3] = fill.a;
    }
}

std::size_t canvas::index(int x, int y) const {
    return (static_cast<std::size_t>(y) * static_cast<std::size_t>(width_) +
            static_cast<std::size_t>(x)) *
           4;
}

rgba8 canvas::get(int x, int y) const {
    const std::size_t i = index(x, y);
    return {rgba_[i], rgba_[i + 1], rgba_[i + 2], rgba_[i + 3]};
}

void canvas::set(int x, int y, rgba8 c) {
    if (x < 0 || y < 0 || x >= width_ || y >= height_) {
        return;
    }
    const std::size_t i = index(x, y);
    rgba_[i] = c.r;
    rgba_[i + 1] = c.g;
    rgba_[i + 2] = c.b;
    rgba_[i + 3] = c.a;
}

void canvas::fill_rect(int x, int y, int w, int h, rgba8 c) {
    for (int yy = std::max(0, y); yy < std::min(height_, y + h); ++yy) {
        for (int xx = std::max(0, x); xx < std::min(width_, x + w); ++xx) {
            set(xx, yy, c);
        }
    }
}

void canvas::draw(const canvas& src, int x, int y) {
    for (int sy = 0; sy < src.height(); ++sy) {
        const int dy = y + sy;
        if (dy < 0 || dy >= height_) {
            continue;
        }
        for (int sx = 0; sx < src.width(); ++sx) {
            const int dx = x + sx;
            if (dx < 0 || dx >= width_) {
                continue;
            }
            const rgba8 s = src.get(sx, sy);
            if (s.a == 255) {
                set(dx, dy, s);
                continue;
            }
            if (s.a == 0) {
                continue;
            }
            const rgba8 d = get(dx, dy);
            const unsigned a = s.a;
            const unsigned out_a = a + d.a * (255u - a) / 255u;
            set(dx, dy,
                {blend(s.r, d.r, a), blend(s.g, d.g, a), blend(s.b, d.b, a),
                 static_cast<std::uint8_t>(out_a)});
        }
    }
}

canvas canvas::magnified(int factor) const {
    canvas out(width_ * factor, height_ * factor, {0, 0, 0, 0});
    for (int y = 0; y < out.height(); ++y) {
        for (int x = 0; x < out.width(); ++x) {
            out.set(x, y, get(x / factor, y / factor));
        }
    }
    return out;
}

void canvas::transform(const std::function<rgb8(rgb8)>& f) {
    for (std::size_t i = 0; i < rgba_.size(); i += 4) {
        const rgb8 out = f({rgba_[i], rgba_[i + 1], rgba_[i + 2]});
        rgba_[i] = out.r;
        rgba_[i + 1] = out.g;
        rgba_[i + 2] = out.b;
    }
}

void canvas::text(int x, int y, const std::string& s, int scale, rgba8 colour) {
    int cx = x;
    for (char c : s) {
        const glyph* g = find_glyph(c);
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if ((g->rows[row] >> (4 - col)) & 1) {
                    fill_rect(cx + col * scale, y + row * scale, scale, scale, colour);
                }
            }
        }
        cx += 6 * scale;
    }
}

int canvas::text_width(const std::string& s, int scale) {
    return s.empty() ? 0 : static_cast<int>(s.size()) * 6 * scale - scale;
}

int canvas::text_height(int scale) {
    return 7 * scale;
}

