std::function<rgb8(rgb8)> cached(std::function<vec3(vec3)> f) {
    auto cache = std::make_shared<std::map<std::uint32_t, rgb8>>();
    return [cache, f](rgb8 c) {
        const std::uint32_t key = (std::uint32_t(c.r) << 16) | (std::uint32_t(c.g) << 8) | c.b;
        auto it = cache->find(key);
        if (it != cache->end()) {
            return it->second;
        }
        const rgb8 out = from_linear(f(to_linear(c)));
        cache->emplace(key, out);
        return out;
    };
}

